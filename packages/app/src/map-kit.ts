// What every map on every page needs: a basemap style, the icon set, and the
// MapLibre constructor behind the viewer's factory seam.

// maplibre-gl 6 has no default export; `Map` is named.
import { Map as MapLibreMap } from "maplibre-gl";
import type { IconSource } from "@livemap/renderer";
import type { MapFactory } from "@livemap/viewer";
import { ICON_SVGS } from "./icons.js";

/** No tiles, one background layer. For `?basemap=blank`, and for working offline. */
const BLANK_STYLE = {
  version: 8 as const,
  glyphs: "https://tiles.openfreemap.org/fonts/{fontstack}/{range}.pbf",
  sources: {},
  layers: [
    {
      id: "bg",
      type: "background" as const,
      paint: { "background-color": "#EAE6DF" },
    },
  ],
};

const OPENFREEMAP = "https://tiles.openfreemap.org/styles/positron";

/**
 * One basemap for now, whatever style id a map carries: the id is stored so a
 * tenant's house style can be resolved later without a migration.
 */
export function resolveStyle(): string | object {
  const blank =
    new URLSearchParams(location.search).get("basemap") === "blank";
  return blank ? BLANK_STYLE : OPENFREEMAP;
}

export const icons: IconSource = {
  resolve: async (id) => ICON_SVGS[id] ?? null,
};

export const mapFactory: MapFactory = {
  create: (o) =>
    new MapLibreMap({
      container: o.container,
      style: o.style as never,
      center: o.center,
      zoom: o.zoom,
      bearing: o.bearing,
      pitch: o.pitch,
      interactive: o.interactive,
      attributionControl: { compact: true },
    }) as never,
};

/** Tenant and map slugs are generated by the server from this alphabet. */
export const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,80}$/;

export function artifactUrls(base: string, tenant: string, map: string) {
  const root = `${base}/t/${tenant}/m/${map}`;
  return {
    root,
    pointer: `${root}/latest.json`,
    version: (n: number) => `${root}/v/${n}.json`,
  };
}

export function embedUrl(tenant: string, map: string, embedId?: string): string {
  const q = new URLSearchParams({ t: tenant, m: map });
  if (embedId) q.set("embedId", embedId);
  return `/embed.html?${q}`;
}
