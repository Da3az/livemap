-- 0001_init — additive only, against an empty database.
-- Specified in docs/data-model.md §7.

begin;

create extension if not exists postgis;
create extension if not exists pgcrypto;
create extension if not exists citext;

-- Application role. Deliberately NOT the table owner: a table owner bypasses
-- row-level security unless FORCE is set, so owning the tables would make the
-- tenant isolation below decorative. Password comes from the migration runner
-- via a session GUC so it never lands in version control.
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'livemap_app') then
    execute format(
      'create role livemap_app login password %L',
      current_setting('livemap.app_password')
    );
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Tenancy and identity
-- ---------------------------------------------------------------------------

create table tenants (
  id             uuid primary key default gen_random_uuid(),
  slug           text not null unique,
  name           text not null,
  default_dir    text not null default 'ltr'
                   check (default_dir in ('ltr','rtl')),
  default_locale text not null default 'en',
  created_at     timestamptz not null default now()
);

create table users (
  id         uuid primary key default gen_random_uuid(),
  email      citext not null unique,
  name       text not null,
  created_at timestamptz not null default now()
);

-- A user may belong to several tenants, so role lives on the join.
create table memberships (
  tenant_id  uuid not null references tenants(id) on delete cascade,
  user_id    uuid not null references users(id)   on delete cascade,
  role       text not null
               check (role in ('owner','admin','editor','contributor','viewer')),
  created_at timestamptz not null default now(),
  primary key (tenant_id, user_id)
);

create index memberships_user_idx on memberships (user_id);

-- ---------------------------------------------------------------------------
-- House style and uploads
-- ---------------------------------------------------------------------------

create table themes (
  id         uuid primary key default gen_random_uuid(),
  tenant_id  uuid not null references tenants(id) on delete cascade,
  name       text not null,
  palette    jsonb not null default '{}'::jsonb,
  fonts      jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (tenant_id, name)
);

create index themes_tenant_idx on themes (tenant_id);

create table assets (
  id          uuid primary key default gen_random_uuid(),
  tenant_id   uuid not null references tenants(id) on delete cascade,
  kind        text not null check (kind in ('icon','sprite','font')),
  name        text not null,
  mime        text not null,
  byte_size   int  not null check (byte_size > 0),
  storage_key text not null,
  -- Content hash, so re-uploading an identical file is a no-op.
  sha256      text not null,
  created_at  timestamptz not null default now(),
  unique (tenant_id, kind, name)
);

create index assets_tenant_idx on assets (tenant_id);

-- ---------------------------------------------------------------------------
-- Maps and features
-- ---------------------------------------------------------------------------

create table maps (
  id         uuid primary key default gen_random_uuid(),
  tenant_id  uuid not null references tenants(id) on delete cascade,
  slug       text not null,
  title      text not null,
  title_dir  text not null default 'auto'
               check (title_dir in ('ltr','rtl','auto')),
  ui_dir     text not null default 'ltr'
               check (ui_dir in ('ltr','rtl','auto')),

  center     geography(Point, 4326) not null,
  zoom       real not null check (zoom between 0 and 24),
  bearing    real not null default 0,
  pitch      real not null default 0,

  basemap_style_id text not null,
  label_langs      text[] not null default array['en'],

  theme_id   uuid references themes(id) on delete set null,

  -- Optimistic concurrency: a write carries the rev it read, and loses if stale.
  rev        bigint not null default 0,
  published_version int,

  archived_at timestamptz,
  created_by  uuid not null references users(id),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),

  unique (tenant_id, slug)
);

create index maps_tenant_idx on maps (tenant_id);

create table features (
  -- text, not uuid: feature ids are generated by the editor before any round
  -- trip, so the client can render a new shape optimistically. A server-side
  -- uuid default could never be the source of truth for them.
  --
  -- Scoped by map, not globally unique. Client-generated ids collide across
  -- tenants eventually, and with a global primary key that collision turns an
  -- upsert into a cross-tenant conflict that RLS rejects.
  id        text not null,
  map_id    uuid not null references maps(id) on delete cascade,
  tenant_id uuid not null references tenants(id) on delete cascade,

  kind      text not null
              check (kind in ('area','line','arrow','frontline','point','annotation')),

  -- Fractional index: reordering one feature is a single-row write.
  -- See packages/core/src/order.ts for the subdividability invariant.
  at        text not null,

  -- Authored geometry. For an arrow these are the CONTROL POINTS, not the
  -- rendered curve.
  geom      geography(Geometry, 4326),

  -- Kind-specific payload and the full per-feature style. Only the spatial
  -- part is a real column; the open-ended style payload stays JSON.
  props     jsonb not null default '{}'::jsonb,

  updated_by uuid references users(id),
  updated_at timestamptz not null default now(),

  primary key (map_id, id)
);

create index features_map_order_idx on features (map_id, at);
create index features_geom_idx      on features using gist (geom);
create index features_tenant_idx    on features (tenant_id);

-- ---------------------------------------------------------------------------
-- Versions and publishing
-- ---------------------------------------------------------------------------

create table map_versions (
  map_id        uuid not null references maps(id) on delete cascade,
  version       int  not null,
  tenant_id     uuid not null references tenants(id) on delete cascade,

  -- Content hash of the artifact, served as the ETag. Excludes published_at and
  -- published_by so republishing an unchanged map keeps reader caches warm.
  etag          text not null,
  storage_key   text not null,
  byte_size     int  not null,
  feature_count int  not null,

  published_at  timestamptz not null default now(),
  published_by  uuid not null references users(id),
  note          text,

  primary key (map_id, version)
);

create index map_versions_lookup_idx on map_versions (map_id, version desc);
create index map_versions_tenant_idx on map_versions (tenant_id);

create table publish_requests (
  id           uuid primary key default gen_random_uuid(),
  map_id       uuid not null references maps(id) on delete cascade,
  tenant_id    uuid not null references tenants(id) on delete cascade,
  requested_by uuid not null references users(id),
  requested_at timestamptz not null default now(),
  state        text not null default 'pending'
                 check (state in ('pending','approved','rejected','withdrawn')),
  decided_by   uuid references users(id),
  decided_at   timestamptz,
  comment      text
);

create index publish_requests_map_idx    on publish_requests (map_id, state);
create index publish_requests_tenant_idx on publish_requests (tenant_id);

-- ---------------------------------------------------------------------------
-- Live ingest
-- ---------------------------------------------------------------------------

create table feeds (
  id            uuid primary key default gen_random_uuid(),
  tenant_id     uuid not null references tenants(id) on delete cascade,
  map_id        uuid not null references maps(id) on delete cascade,
  kind          text not null check (kind in ('csv','geojson','sheet','http')),
  url           text not null,
  -- Cadence is the pricing axis, so it is enforced here rather than in
  -- application code.
  interval_secs int not null check (interval_secs >= 60),
  -- false = fetch and stage for approval; true = publish automatically.
  auto_publish  boolean not null default false,
  last_fetch_at timestamptz,
  last_etag     text,
  last_error    text,
  enabled       boolean not null default true
);

create index feeds_tenant_idx on feeds (tenant_id);
create index feeds_due_idx    on feeds (enabled, last_fetch_at);

-- ---------------------------------------------------------------------------
-- Row-level security
--
-- Every policy reads app.tenant_id, set per request. When it is unset,
-- nullif(...) yields NULL, the comparison is NULL, and no rows match — the
-- failure mode is an empty result, never another tenant's data.
-- ---------------------------------------------------------------------------

create or replace function livemap_current_tenant() returns uuid
language sql stable
as $$ select nullif(current_setting('app.tenant_id', true), '')::uuid $$;

alter table tenants          enable row level security;
alter table users            enable row level security;
alter table memberships      enable row level security;
alter table themes           enable row level security;
alter table assets           enable row level security;
alter table maps             enable row level security;
alter table features         enable row level security;
alter table map_versions     enable row level security;
alter table publish_requests enable row level security;
alter table feeds            enable row level security;

-- Belt and braces: FORCE makes the policies apply even to the table owner, so
-- a migration or a psql session cannot quietly read across tenants either.
alter table tenants          force row level security;
alter table users            force row level security;
alter table memberships      force row level security;
alter table themes           force row level security;
alter table assets           force row level security;
alter table maps             force row level security;
alter table features         force row level security;
alter table map_versions     force row level security;
alter table publish_requests force row level security;
alter table feeds            force row level security;

create policy tenant_isolation on tenants
  using (id = livemap_current_tenant())
  with check (id = livemap_current_tenant());

-- Users are global, so visibility is granted by a shared membership rather
-- than by a tenant_id column.
create policy tenant_isolation on users
  using (
    exists (
      select 1 from memberships m
      where m.user_id = users.id
        and m.tenant_id = livemap_current_tenant()
    )
  );

create policy tenant_isolation on memberships
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on themes
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on assets
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on maps
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on features
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on map_versions
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on publish_requests
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

create policy tenant_isolation on feeds
  using (tenant_id = livemap_current_tenant())
  with check (tenant_id = livemap_current_tenant());

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------

grant usage on schema public to livemap_app;
grant select, insert, update, delete on all tables in schema public to livemap_app;
grant execute on function livemap_current_tenant() to livemap_app;

-- Provisioning a tenant is inherently cross-tenant: there is no app.tenant_id
-- to set until the row exists. So the migration/admin role bypasses RLS and
-- the application role never can. FORCE above keeps the policies applying to
-- any other owner, which is what stops a future `alter table ... owner to
-- livemap_app` from silently disabling isolation.
do $$
begin
  execute format('alter role %I bypassrls', current_user);
end $$;

commit;
