/** Words for the map settings pane. Composed into `editor-extras.ts`. */

function arabicFeatures(n: number): string {
  if (n === 1) return "عنصر واحد";
  if (n === 2) return "عنصران";
  if (n % 100 >= 3 && n % 100 <= 10) return `${n} عناصر`;
  return `${n} عنصرًا`;
}

