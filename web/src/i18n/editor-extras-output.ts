/** Words for import, export and the preview. Composed into `editor-extras.ts`. */

type Kind = "area" | "line" | "arrow" | "frontline" | "point" | "annotation";

function plural(n: number, one: string, many: string): string {
  return n === 1 ? `1 ${one}` : `${n} ${many}`;
}

function arabicCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n % 100 >= 3 && n % 100 <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

const arabicFeatures = (n: number): string => arabicCount(n, "عنصر واحد", "عنصران", "عناصر", "عنصرًا");

const kindsEn: Record<Kind, (n: number) => string> = {
  area: (n) => plural(n, "area", "areas"),
  line: (n) => plural(n, "line", "lines"),
  arrow: (n) => plural(n, "arrow", "arrows"),
  frontline: (n) => plural(n, "front line", "front lines"),
  point: (n) => plural(n, "icon", "icons"),
  annotation: (n) => plural(n, "text", "texts"),
};

const kindsAr: Record<Kind, (n: number) => string> = {
  area: (n) => arabicCount(n, "منطقة واحدة", "منطقتان", "مناطق", "منطقة"),
  line: (n) => arabicCount(n, "خط واحد", "خطّان", "خطوط", "خطًّا"),
  arrow: (n) => arabicCount(n, "سهم واحد", "سهمان", "أسهم", "سهمًا"),
  frontline: (n) => arabicCount(n, "خط جبهة واحد", "خطّا جبهة", "خطوط جبهة", "خط جبهة"),
  point: (n) => arabicCount(n, "رمز واحد", "رمزان", "رموز", "رمزًا"),
  annotation: (n) => arabicCount(n, "نص واحد", "نصّان", "نصوص", "نصًّا"),
};

